/* ============================================================================
   Mobile Parts Finder · scripts/build-cloudflare.js
   ----------------------------------------------------------------------------
   Assembles the site for Cloudflare Pages, where requests for static files
   are free and unlimited:

     node scripts/build-cloudflare.js
     cd .cloudflare && npx wrangler pages deploy public --project-name mobile-parts-finder

   WHAT IS SERVED. Exactly what vercel.json's `builds` serves statically —
   the same tracked files, nothing from api/, scripts/ or data/.

   CLEAN URLS. Vercel serves /model/x from model/x/index.html and removes a
   trailing slash. Pages instead adds one to a folder. So every
   <dir>/index.html is written as <dir>.html, which Pages serves at /<dir>
   with no slash — the canonical URLs every page and sitemap already carry.

   THE SERVERLESS HALF. api/*.js needs Node and stays on Vercel. The Pages
   Functions in cloudflare/functions/ forward /api/* and /i/* to API_ORIGIN
   (the Vercel deployment), answer /api/firebase-config themselves, and proxy
   /__/auth/* to Firebase. With API_ORIGIN unset, those features answer 503
   and the catalogue keeps working.

   vercel.json's routes are mirrored in _redirects and _headers below; a
   route added there needs its line here too.
   ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, '.cloudflare');
const PUBLIC = path.join(OUT, 'public');

/* the static sources, as vercel.json lists them */
const vercel = JSON.parse(fs.readFileSync(path.join(ROOT, 'vercel.json'), 'utf8'));
const patterns = vercel.builds.filter(b => b.use === '@vercel/static').map(b => b.src);
const matches = file => patterns.some(p => p.endsWith('/**') ? file.startsWith(p.slice(0, -2)) : file === p);

const REDIRECTS = `# Generated by scripts/build-cloudflare.js — mirrors vercel.json routes
/about /mobile-parts-finder 308
/o/:token /order 200
/admin/* /admin 200
/account /finder 200
/account/* /finder 200
/group /finder 200
/group/* /finder 200
/billing /finder 200
/billing/* /finder 200
`;

const HEADERS = `# Generated by scripts/build-cloudflare.js — mirrors vercel.json routes
/assets/brand/*
  Cache-Control: public, max-age=604800
/assets/brands/*
  Cache-Control: public, max-age=604800
/assets/categories/*
  Cache-Control: public, max-age=604800
/assets/dataset.json
  Cache-Control: public, max-age=300, stale-while-revalidate=86400
/assets/search-index.json
  Cache-Control: public, max-age=300, stale-while-revalidate=86400
`;

function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  const files = execFileSync('git', ['ls-files', '-z'], { cwd: ROOT, encoding: 'utf8' })
    .split('\0').filter(Boolean).filter(f => matches(f) && !/\.test\.js$/.test(f));

  let flattened = 0;
  files.forEach(f => {
    let dest = f;
    const m = f.match(/^(.+)\/index\.html$/);
    if (m) { dest = m[1] + '.html'; flattened++; }
    const to = path.join(PUBLIC, dest);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(path.join(ROOT, f), to);
  });
  fs.writeFileSync(path.join(PUBLIC, '_redirects'), REDIRECTS);
  fs.writeFileSync(path.join(PUBLIC, '_headers'), HEADERS);
  fs.cpSync(path.join(ROOT, 'cloudflare', 'functions'), path.join(OUT, 'functions'), { recursive: true });

  const count = files.length + 2;
  console.log(`\n  Cloudflare Pages bundle -> .cloudflare/public`);
  console.log(`  files            ${count} (limit 20,000)`);
  console.log(`  pages flattened  ${flattened}`);
  console.log(`  functions        .cloudflare/functions\n`);
  if (count > 20000) { console.error('  over the free plan\'s 20,000 files'); process.exit(1); }
}

main();
